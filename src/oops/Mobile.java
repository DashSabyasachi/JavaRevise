package oops;

public class Mobile {

    // Private variables
    private String brand;
    private String model;
    private int price;

    // Setter
    public void setBrand(String brand) {
        this.brand = brand;
    }

    // Getter
    public String getBrand() {
        return brand;
    }

    // Setter
    public void setModel(String model) {
        this.model = model;
    }

    // Getter
    public String getModel() {
        return model;
    }

    // Setter
    public void setPrice(int price) {
        this.price = price;
    }

    // Getter
    public int getPrice() {
        return price;
    }
}